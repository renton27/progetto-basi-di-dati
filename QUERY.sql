-- 12)Rilevamento discrepanze tra competenze dei tecnici e competenze necessarie
-- (Assumiamo che l’azienda abbia bisogno di assumere se possiede meno di 15 tecnici per quella singola competenza
-- o se  il ratio guasti/tecnico risulta maggiore di 8.40)
SELECT 
    TC.ID_COMPETENZA,
    COUNT(DISTINCT ID_TECNICO) AS NTECNICI,
    COUNT(DISTINCT GC.ID_GUASTO) AS NGUASTI,
    ROUND( COUNT(DISTINCT ID_GUASTO) / COUNT(DISTINCT ID_TECNICO), 2) AS GUASTI_PER_TECNICO
FROM TECNICO_COMPETENZA TC
JOIN GUASTO_COMPETENZA GC ON TC.ID_COMPETENZA = GC.ID_COMPETENZA
GROUP BY TC.ID_COMPETENZA
HAVING NTECNICI < 15 OR GUASTI_PER_TECNICO > 8.40;

