-- 9)Assegnare il ritiro dei modem guasti ai tecnici disponibili

INSERT INTO RITIRO (DETTAGLI, DATARITIRO, ID_MODEM, ID_TECNICO)  
SELECT DISTINCT NULL, CURDATE(), M.ID AS MODEMID, T.ID AS TECNICOID
FROM MODEM M
JOIN PERCORSOCLIENTE PC ON PC.MODEM_ID = M.ID
JOIN CENTRALE C ON C.ID = PC.CENTRALE_ID
JOIN TECNICO T ON T.ID_TERRITORIO = C.ID_TERRITORIO
WHERE M.STATO = 'GUASTO' AND T.DISPONIBILITA = 'ATTIVO';


