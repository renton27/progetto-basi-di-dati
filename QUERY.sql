-- 1)Conoscere per ciascuna competenza il numero di tecnici a disposizione

SELECT C.ID, COUNT(T.ID_TECNICO) AS NUMEROTECNICI
FROM COMPETENZA C LEFT JOIN TECNICO_COMPETENZA T
ON C.ID=T.ID_COMPETENZA
GROUP BY C.ID;

-- 2)Conoscere il numero clienti per ciascuna zona disservita (permette di conoscere anche il numero di clienti per antenna)

CREATE TEMPORARY TABLE NCLIENTI_ANTENNE AS
SELECT DISTINCT COUNT(*) AS NCLIENTI, PC.ANTENNA_ID AS ANTENNA FROM MODEM M
JOIN PERCORSOCLIENTE PC ON M.ID = PC.MODEM_ID
WHERE (M.CAVO_ID IS NULL AND PC.CAVO_ID IS NULL)
GROUP BY PC.ANTENNA_ID;

SELECT A.REGIONE, A.PROVINCIA, A.COMUNE, NCA.NCLIENTI, A.ID AS 'ANTENNA' FROM ANTENNA A
JOIN NCLIENTI_ANTENNE NCA ON NCA.ANTENNA = A.ID; 

-- 3)Conoscere per ciascun contratto il relativo costo di attivazione e il costo mensile

CREATE TEMPORARY TABLE COSTODATI AS
SELECT D.COSTODIATTIVAZIONE AS CA_DATI, D.COSTOMENSILE AS CM_DATI,  CONTRATTO_ID AS CONTRATTO FROM CONTRATTO_DATI CD
JOIN DATI D ON D.ID = CD.DATI_ID
ORDER BY CD.CONTRATTO_ID ASC;

CREATE TEMPORARY TABLE COSTOFONIA AS
SELECT F.COSTOATTIVAZIONE AS CA_FONIA, F.COSTOMENSILE AS CM_FONIA, CONTRATTO_ID AS CONTRATTO FROM CONTRATTO_FONIA CF
JOIN FONIA F ON F.ID = CF.FONIA_ID
ORDER BY CF.CONTRATTO_ID ASC;

SELECT  CD.CONTRATTO, ROUND(SUM(CF.CA_FONIA+CD.CA_DATI), 2) AS 'COSTOATTIVAZIONEPACCHETTO', ROUND(SUM(CD.CM_DATI + CF.CM_FONIA), 2) AS 'COSTOMENSILEPACCHETTO', C.COSTORESCISSIONE FROM COSTOFONIA CF
JOIN COSTODATI CD ON CD.CONTRATTO = CF.CONTRATTO
JOIN CONTRATTO C ON C.ID = CF.CONTRATTO
GROUP BY CD.CONTRATTO;


-- 4) Mostrare ID, Nome, Cognome, Area di Competenza e tempo medio di risoluzione dei guasti,
-- tenendo conto che non tutti i guasti hanno importanza uguale; dati i seguenti pesi per ogni livello di guasto: 
-- (0.10 bassa, 0.20 media, 0.30 alta, 0.40 top), fare la media ponderata con il tempo di risoluzione. 
-- Usare la tabella Storico Guasto.

CREATE VIEW TECCOMP AS SELECT ID_TECNICO, GROUP_CONCAT(ID_COMPETENZA) AS AREACOMPETENZA
FROM TECNICO_COMPETENZA
GROUP BY ID_TECNICO;

SELECT T.ID, T.NOME,T.COGNOME, TC.AREACOMPETENZA,
ROUND(SUM(SG.TEMPODIRISOLUZIONE * VG.NUMERO)/COUNT(*),2) AS TEMPOMEDIOPERGUASTO FROM ((STORICOGUASTO SG
RIGHT JOIN TECNICO T ON SG.TECNICOASSEGNATO = T.ID)
JOIN TECCOMP TC ON T.ID = TC.ID_TECNICO)
JOIN VALOREGUASTO VG ON VG.VALORE = SG.PRIORITAGUASTO
GROUP BY T.ID
ORDER BY T.ID;


-- 5)Controllare per ciascuna infrastruttura ( antenna, cavo, ripartilinea) il numero di guasti segnalati su tale linea

SELECT 'CAVO' AS TIPOELEMENTO, PC.CAVO_ID AS IDELEMENTO, COUNT(G.ID) AS NGUASTI FROM PERCORSOCLIENTE PC
JOIN GUASTO G ON PC.ID = G.ID_PERCORSOCLIENTE AND G.ELEMENTOGUASTO = 'CAVO' 
WHERE PC.CAVO_ID IS NOT NULL 
GROUP BY PC.CAVO_ID
UNION ALL
SELECT 'RIPARTILINEA' AS TIPOELEMENTO, PC.RIPARTILINEA_ID AS IDELEMENTO, COUNT(G.ID) AS NGUASTI FROM PERCORSOCLIENTE PC
JOIN GUASTO G ON PC.ID = G.ID_PERCORSOCLIENTE AND G.ELEMENTOGUASTO = 'RIPARTILINEA' 
WHERE PC.RIPARTILINEA_ID IS NOT NULL 
GROUP BY PC.RIPARTILINEA_ID
UNION ALL
SELECT 'CENTRALE' AS TIPOELEMENTO, PC.CENTRALE_ID AS IDELEMENTO, COUNT(G.ID) AS NGUASTI FROM PERCORSOCLIENTE PC
JOIN GUASTO G ON PC.ID = G.ID_PERCORSOCLIENTE AND G.ELEMENTOGUASTO = 'CENTRALE' 
WHERE PC.CENTRALE_ID IS NOT NULL 
GROUP BY PC.CENTRALE_ID
UNION ALL
SELECT 'ANTENNA' AS TIPOELEMENTO, PC.ANTENNA_ID AS IDELEMENTO, COUNT(G.ID) AS NGUASTI FROM PERCORSOCLIENTE PC
JOIN GUASTO G ON PC.ID = G.ID_PERCORSOCLIENTE AND G.ELEMENTOGUASTO = 'ANTENNA' 
WHERE PC.ANTENNA_ID IS NOT NULL 
GROUP BY PC.ANTENNA_ID
UNION ALL
SELECT 'MODEM' AS TIPOELEMENTO, PC.MODEM_ID AS IDELEMENTO, COUNT(G.ID) AS NGUASTI FROM PERCORSOCLIENTE PC
JOIN GUASTO G ON PC.ID = G.ID_PERCORSOCLIENTE AND G.ELEMENTOGUASTO = 'MODEM' 
WHERE PC.MODEM_ID IS NOT NULL 
GROUP BY PC.MODEM_ID
ORDER BY TIPOELEMENTO ASC, IDELEMENTO ASC, NGUASTI ASC;


-- 6)Controllare il numero ed il tipo operazioni che ciascun tecnico ha eseguito

SELECT 
    T.ID AS TECNICO_ID,
    TG.OP_GUASTO AS OP_GUASTO,
    TA.OP_ATTIVAZIONE AS OP_ATTIVAZIONE,
    TR.OP_RITIRO AS OP_RITIRO
FROM TECNICO T
LEFT JOIN
    (SELECT TECNICO_ID, COUNT(GUASTO_ID) AS OP_GUASTO FROM TECNICO_GUASTO GROUP BY TECNICO_ID) TG
ON T.ID = TG.TECNICO_ID
LEFT JOIN 
    (SELECT ID_TECNICO AS TECNICO_ID, COUNT(ID_ATTIVAZIONE) AS OP_ATTIVAZIONE FROM TECNICO_ATTIVAZIONE GROUP BY ID_TECNICO) TA
ON TG.TECNICO_ID = TA.TECNICO_ID
LEFT JOIN 
    (SELECT ID_TECNICO AS TECNICO_ID, COUNT(ID_MODEM) AS OP_RITIRO FROM RITIRO GROUP BY ID_TECNICO) TR
ON TG.TECNICO_ID =TR.TECNICO_ID;



-- 7)Assegnare le nuove attivazioni ai tecnici disponibili

CREATE TEMPORARY TABLE PC AS SELECT PERCORSOCLIENTE_ID, ID
FROM ATTIVAZIONE
WHERE STATO ='DA FARE';

CREATE TEMPORARY TABLE IDC AS SELECT P.CENTRALE_ID, P.ID
FROM PERCORSOCLIENTE P
WHERE (P.ID IN (SELECT PC.PERCORSOCLIENTE_ID FROM PC)) AND P.CENTRALE_ID IS NOT NULL;

CREATE TEMPORARY TABLE IDA AS SELECT P.ANTENNA_ID, P.ID
FROM PERCORSOCLIENTE P
WHERE (P.ID IN (SELECT PC.PERCORSOCLIENTE_ID FROM PC)) AND P.ANTENNA_ID IS NOT NULL;

CREATE TEMPORARY TABLE IDT AS (SELECT C.ID_TERRITORIO, C.ID
FROM CENTRALE C
WHERE C.ID IN (SELECT IDC.CENTRALE_ID FROM IDC))
UNION
(SELECT A.ID_TERRITORIO, A.ID FROM ANTENNA A
WHERE A.ID IN (SELECT IDA.ANTENNA_ID FROM IDA));

CREATE TEMPORARY TABLE TECTER AS SELECT T.ID, T.ID_TERRITORIO
FROM TECNICO T
WHERE (T.ID_TERRITORIO IN (SELECT IDT.ID_TERRITORIO FROM IDT)) AND T.DISPONIBILITA = 'ATTIVO';

INSERT INTO TECNICO_ATTIVAZIONE (ID_ATTIVAZIONE, ID_TECNICO)
(SELECT PC.ID AS IDATTIVAZIONE, TECTER.ID AS IDTECNICO
FROM (((PC JOIN IDC ON PC.PERCORSOCLIENTE_ID = IDC.ID) JOIN IDT ON IDC.CENTRALE_ID = IDT.ID)
JOIN TECTER ON IDT.ID_TERRITORIO = TECTER.ID_TERRITORIO)
LIMIT 1);

INSERT INTO TECNICO_ATTIVAZIONE (ID_ATTIVAZIONE, ID_TECNICO)
(SELECT PC.ID AS IDATTIVAZIONE, TECTER.ID AS IDTECNICO
FROM (((PC JOIN IDA ON PC.PERCORSOCLIENTE_ID = IDA.ID) JOIN IDT ON IDA.ANTENNA_ID = IDT.ID)
